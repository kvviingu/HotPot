#!/bin/bash
# Install or update the FRONT VM (public: Cowrie SSH/Telnet, web honeypot, decoys, IDS, Squid for the
# backend). Run as root from an unpacked copy of the repo that contains honeypot.conf:
#     sudo bash install/front.sh                 install or update (deploy.sh does this over SSH)
#     sudo bash install/front.sh --check         preflight checks only, changes nothing
#     sudo bash install/front.sh --confirm-ssh   after the first run: admin SSH works on the new port
#     sudo bash install/front.sh --revert-ssh    put admin SSH back on port 22 now
# Safe to re-run; it keeps generated secrets and collected data. Log: /var/log/hotpot-install.log
set -euo pipefail
SRC=$(cd "$(dirname "$0")/.." && pwd)
DEST=/opt/honeypot
source "$SRC/install/lib.sh"
source "$SRC/install/preflight.sh"
source "$SRC/install/sshmove.sh"

MODE=install
case "${1:-}" in
  "") ;;
  --check) MODE=check ;;
  --confirm-ssh) MODE=confirm ;;
  --revert-ssh) MODE=revert ;;
  *) die "unknown option $1 (use --check, --confirm-ssh or --revert-ssh)" ;;
esac

need_root
load_conf "$SRC/honeypot.conf"
require_vars FRONT_PUBLIC_IP FRONT_PRIVATE_IP ADMIN_SSH_PORT BACKEND_ENABLED
[ "$BACKEND_ENABLED" = 1 ] && require_vars BACKEND_IP BACKEND_SSH_PORT BACKEND_TELNET_PORT

if [ "$MODE" = check ]; then preflight_front; exit $?; fi
if [ "$MODE" = revert ]; then ssh_revert_now; echo "Admin SSH is back on port 22 only."; exit 0; fi

start_log front.sh "$@"
need_supported_os
preflight_front || exit 1

# ---- 1. admin SSH off port 22 (Cowrie takes 22) -----------------------------------------------------
# Two steps with an automatic undo, so a cloud firewall that blocks the new port cannot lock you out.
if [ "$MODE" = confirm ]; then
  ssh_move_finish
elif ! ssh_moved; then
  ssh_move_begin
  cloud=$(detect_cloud)
  cat <<EOF

$(ok "Step 1 of 2 done:") admin SSH now listens on port 22 and on port $ADMIN_SSH_PORT.
  Check that the new port works from your own computer, in a NEW terminal:
      ssh -p $ADMIN_SSH_PORT ${SUDO_USER:-${SSH_USER:-root}}@$FRONT_PUBLIC_IP
  If it does, run this in that session to finish the install:
      sudo bash $SRC/install/front.sh --confirm-ssh
  If it does not, allow TCP $ADMIN_SSH_PORT from your IP in:
      $(cloud_firewall_hint "$cloud")
  Nothing to undo by hand: without confirmation, SSH goes back to port 22 only in $SSH_PROBATION_MIN minutes.
  (./deploy.sh front does all of this for you.)
EOF
  exit 3
fi

# ---- 2. packages ------------------------------------------------------------------------------------
ensure_docker
# zip: sample downloads as password-protected zips; yara and file: the dashboard scans samples here
pkg_install zip yara file openssl iproute curl

# ---- 3. files ---------------------------------------------------------------------------------------
step "Copying the honeypot to $DEST"
mkdir -p "$DEST"
ids_sum() { cat "$DEST"/ids/suricata.yaml "$DEST"/ids/disable.conf 2>/dev/null | sha256sum; }
IDS_BEFORE=$(ids_sum)
cowrie_sum() { find "$DEST"/cowrie/patches "$DEST"/cowrie/honeyfs -type f 2>/dev/null | sort | xargs -r cat | sha256sum; }
COWRIE_BEFORE=$(cowrie_sum)
# the persona's files are replaced as a whole, so renamed paths (a new identity) leave nothing behind
rm -rf "$DEST/cowrie/honeyfs"
(cd "$SRC" && tar cf - docker-compose.yml cowrie web egress decoys ids) | (cd "$DEST" && tar xf - --no-same-owner)
strip_cr "$DEST/docker-compose.yml" "$DEST/cowrie" "$DEST/web" "$DEST/egress" "$DEST/decoys" "$DEST/ids"
IDS_CHANGED=0
[ "$IDS_BEFORE" = "$(ids_sum)" ] || IDS_CHANGED=1
COWRIE_CHANGED=0
[ "$COWRIE_BEFORE" = "$(cowrie_sum)" ] || COWRIE_CHANGED=1

# ---- 4. settings and secrets ------------------------------------------------------------------------
step "Writing $DEST/.env"
{
  echo "# generated by install/front.sh from honeypot.conf - edit honeypot.conf and re-deploy instead"
  conf_lines "$SRC/honeypot.conf"
  profiles=""
  if [ "$BACKEND_ENABLED" = 1 ]; then echo "COWRIE_BACKEND=proxy"; profiles=backend; else echo "COWRIE_BACKEND=shell"; fi
  if [ "${DECOYS_ENABLED:-0}" = 1 ]; then profiles="${profiles:+$profiles,}decoys"; fi
  if [ "${IDS_ENABLED:-0}" = 1 ]; then
    profiles="${profiles:+$profiles,}ids"
    # the interface that carries the public traffic (the one holding the private address OCI NATs to)
    echo "IDS_INTERFACE=$(ip -4 -o addr | awk -v ip="$FRONT_PRIVATE_IP" '$4 ~ "^"ip"/" {print $2; exit}')"
  fi
  echo "COMPOSE_PROFILES=$profiles"
} > "$DEST/.env"
chmod 600 "$DEST/.env"

if [ -f "$SRC/secrets/openrouter.env" ]; then
  install -m 600 "$SRC/secrets/openrouter.env" "$DEST/openrouter.env"
  strip_cr "$DEST/openrouter.env"
elif [ ! -f "$DEST/openrouter.env" ]; then
  echo "OPENROUTER_API_KEY=" > "$DEST/openrouter.env"; chmod 600 "$DEST/openrouter.env"
  warn "No secrets/openrouter.env: unknown web paths get a plain 404 instead of an LLM-made page."
fi

if [ "$BACKEND_ENABLED" = 1 ] && [ ! -s "$DEST/backend.env" ]; then
  step "Generating the backend login password ($DEST/backend.env)"
  pass=$(openssl rand -base64 32 | tr -dc 'A-Za-z0-9' | cut -c1-24)
  umask 077
  printf 'BACKEND_PASS=%s\nCOWRIE_PROXY_BACKEND_PASS=%s\n' "$pass" "$pass" > "$DEST/backend.env"
  umask 022
fi

# Squid lets the backend reach only the package mirrors in install/mirrors.txt (+ EXTRA_APT_MIRRORS)
sites=$(setup_sites | paste -sd' ' -)
sed -e "s|\${BACKEND_IP}|${BACKEND_IP:-127.0.0.1}|g" -e "s|\${SETUP_SITES}|$sites|g" \
  "$DEST/egress/squid.conf.template" > "$DEST/egress/squid.conf"

# ---- 5. Cowrie filesystem image of the persona ------------------------------------------------------
cd "$DEST"
COWRIE_IMAGE=$(awk '/image: cowrie\//{print $2; exit}' docker-compose.yml)
if [ ! -f cowrie/fs.pickle ] || [ "$COWRIE_CHANGED" = 1 ] || [ -n "$(find cowrie/build_fs.py -newer cowrie/fs.pickle -print -quit)" ]; then
  step "Building the persona filesystem (cowrie/fs.pickle)"
  docker run --rm --user 0 --entrypoint python3 -v "$DEST/cowrie:/work" "$COWRIE_IMAGE" /work/build_fs.py
fi

# ---- 6. network IDS (Suricata) ----------------------------------------------------------------------
if [ "${IDS_ENABLED:-0}" = 1 ]; then
  chmod 755 "$DEST/ids/maintain.sh"
  if [ ! -s /var/lib/docker/volumes/honeypot_ids-lib/_data/rules/suricata.rules ]; then
    step "Fetching the ET Open rules for Suricata"
    "$DEST/ids/maintain.sh" rules
  elif [ "$IDS_CHANGED" = 1 ]; then
    # suricata.yaml or disable.conf changed: rebuild the rule file, restart Suricata after compose up
    step "IDS settings changed: refreshing the Suricata rules"
    "$DEST/ids/maintain.sh" rules || warn "rule refresh failed; Suricata keeps the previous rules"
  fi
  cat > /etc/systemd/system/hotpot-ids.service <<UNIT
[Unit]
Description=HotPot IDS upkeep: rotate eve.json, refresh Suricata rules
After=docker.service
[Service]
Type=oneshot
ExecStart=$DEST/ids/maintain.sh
UNIT
  cat > /etc/systemd/system/hotpot-ids.timer <<UNIT
[Unit]
Description=Daily HotPot IDS upkeep
[Timer]
OnCalendar=*-*-* 04:20:00 UTC
RandomizedDelaySec=15m
Persistent=true
[Install]
WantedBy=timers.target
UNIT
  systemctl daemon-reload
  systemctl enable --now hotpot-ids.timer >/dev/null
else
  systemctl disable --now hotpot-ids.timer >/dev/null 2>&1 || true
fi

step "Daily clean-up of old logs and samples (hotpot-retention.timer)"
install_retention

# ---- 7. start ---------------------------------------------------------------------------------------
step "Starting containers"
docker compose up -d --build --remove-orphans
# compose only recreates a container when its own definition changes, not its mounted config files
if [ "${IDS_ENABLED:-0}" = 1 ] && [ "$IDS_CHANGED" = 1 ]; then docker restart ids >/dev/null; fi
# Cowrie reads its patches and password list at startup (they are bind-mounted, not baked in)
if [ "$COWRIE_CHANGED" = 1 ]; then step "Cowrie patches or persona changed: restarting Cowrie"; docker restart cowrie >/dev/null; fi
sleep 3
docker compose ps --format 'table {{.Name}}\t{{.Status}}\t{{.Ports}}'

cat <<EOF

$(ok "Front VM ready.")
  Honeypot ports open to the internet: 22 (SSH), 23 (Telnet), 80 and 443 (web).
  Decoy services (if DECOYS_ENABLED=1): 6379 Redis, 2375 Docker API, 9200 Elasticsearch, 3306 MySQL, 11434 Ollama, 6443 Kubernetes API, 3389 RDP, 445 SMB;
  open those in the cloud firewall too.
  Network IDS (if IDS_ENABLED=1): Suricata watches the public interface; it opens no ports.
  Admin SSH: port $ADMIN_SSH_PORT (keep it limited to your own IP in the cloud firewall).
EOF
[ "$BACKEND_ENABLED" = 1 ] && echo "  Next, if not done yet: install the backend VM (./deploy.sh backend); SSH/Telnet logins need it."
exit 0
